export type MessageKey = keyof typeof en;
export type MessageValues = Record<string, string | number>;

const categoryKeys: Record<string, MessageKey> = {
  Wedding: "category.Wedding",
  "Home Decor": "category.Home Decor",
  "Digital Products": "category.Digital Products",
  Gifts: "category.Gifts",
  Jewelry: "category.Jewelry",
  Clothing: "category.Clothing",
  Printable: "category.Printable",
  "Wall Art": "category.Wall Art",
  General: "category.General",
};

export function translateCategory(locale: Locale, category: string): string {
  const key = categoryKeys[category];
  return key ? translate(locale, key) : category;
}

export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && (locales as readonly string[]).includes(value);
}

export function translate(locale: Locale, key: MessageKey, values?: MessageValues): string {
  // Keep a missing/invalid key from crashing the entire client tree. This is
  // especially useful during locale changes and preview hot reloads.
  const safeKey = typeof key === "string" ? key : "";
  const messageKey = safeKey as MessageKey;
  const localized = locale === "tr" ? tr[messageKey] : en[messageKey];
  const fallback = en[messageKey];
  const template = typeof localized === "string"
    ? localized
    : typeof fallback === "string"
      ? fallback
      : safeKey;
  return String(template).replace(/\{([^}]+)\}/g, (_, name: string) => String(values?.[name] ?? `{${name}}`));
}
